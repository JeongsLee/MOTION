"""Latent SEMANTIC COMPOSITION (revision R1-3; A19): are latent fields composable like semantic vectors, and does the
dynamics act correctly on a composed latent?  Background a (a real NS-Sines initial state) and a component b (a
Gaussian vortex on a fluid at rest) are encoded separately; their latents are composed as
    h_comp = h(a) + [h(b) - h(0)]
and the forecast from h_comp is compared with (1) the model's forecast from the real composite input a+b and (2) the
numerical solution of the composite (pseudo-spectral NS, nu and frame interval fitted to NS-Sines; bench/ns_spectral.py).
All trajectories (a, a+b, b, 0) are generated by the solver from frame 0, so the 10-frame histories are physically
consistent; all inputs share ONE normalization (that of a), so latent differences are not rescaling artefacts.
Measures
  encoder additivity : cos / relL2 between h(a+b) - h(a) and h(b) - h(0) (latent of the first step); control: the
                       component shifted to the wrong place (rolled by half the domain)
  (i)  anchor a+b, latent composed  : forecast with h replaced by h_comp at step 1 (h = core output fed to the bank)
  (ii) anchor a,   latent composed  : forecast of a with h(a) -> h_comp at step 1 (pure latent insertion)
  controls for (ii): sign-flipped component, random latent direction with the same per-cell norm
  scores (vorticity of the change relative to the forecast of a, whole domain, steps 1/5/10): correlation and gain
  against the solver's vortex effect  w[S(a+b)] - w[S(a)]  and against the model's own effect  w[P(a+b)] - w[P(a)].
  python latent_compose.py --ckpt C --out OUT.npz
"""
